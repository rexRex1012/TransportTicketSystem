
CREATE TYPE request_type AS ENUM ('PATIENT', 'EQUIPMENT', 'SPECIMEN');

CREATE TYPE request_status AS ENUM ('NEW','ASSIGNED','ACKNOWLEDGED','EN_ROUTE','ARRIVED','PICKED_UP','COMPLETED', 'POSTPONED','CANCELLED');

CREATE TYPE priority AS ENUM ('STAT', 'REGULAR');

CREATE TYPE trip_purpose AS ENUM ('TRANSFER', 'TEST', 'PROCEDURE', 'DISCHARGE');

CREATE TYPE transport_mode AS ENUM ('WHEELCHAIR', 'STRETCHER', 'BED');

CREATE TYPE equipment_type AS ENUM ('BED', 'STRETCHER', 'WHEELCHAIR', 'O2_TANK', 'CODE_CART', 'OTHER');

CREATE TYPE isolation_type AS ENUM ('NONE', 'CONTACT', 'ENTERIC_CONTACT', 'DROPLET', 'AIRBORNE', 'SPECIAL_RESPIRATORY', 'PROTECTIVE');

CREATE TYPE app_role AS ENUM ('STAFF', 'TRANSPORTER', 'DISPATCHER', 'MANAGER', 'ADMIN');

CREATE TYPE transporter_status AS ENUM ('AVAILABLE', 'ON_CALL', 'ON_BREAK', 'INACTIVE', 'SIGNED_OUT');

CREATE TYPE reason_type AS ENUM ('DELAY', 'CANCEL');

CREATE TYPE assigned_by AS ENUM ('ENGINE', 'DISPATCHER');

CREATE TYPE sector_rank AS ENUM ('FIRST', 'SECONDARY');

CREATE TABLE sectors(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code varchar unique not null,  --'ED, MAIN, or SURGICAL'
  name varchar not null);

CREATE TABLE locations(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name  varchar  not null,
  floor varchar not null,  --B,A,1-7
  sector_id integer references sectors(id),
  equipment_only boolean not null default false,
  no_equipment_parking boolean not null default false);

CREATE TABLE departments(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name varchar not null,
 location_id integer not null references locations(id));

CREATE TABLE rooms(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  location_id integer not null references locations(id),
  number varchar not null); --612,n14
CREATE UNIQUE INDEX rooms_location_id_number_key ON rooms(location_id, number);

CREATE TABLE users(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  keycloak_id varchar unique not null,
  name varchar not null,
  role app_role not null,
  department_id integer references departments(id), --staff only
  status transporter_status,  --transporter only
  last_location_id integer references locations(id), --transporter only
  last_call_finished_at timestamptz);  --No passwords. Logins come from Keycloak / AD. Java class: AppUser'

CREATE TABLE patients(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar not null,
  mrn varchar unique not null,
  current_location_id integer references locations(id),
  current_room varchar,
  isolation_type isolation_type not null default 'NONE',
  discharged boolean not null default false);

CREATE TABLE equipment(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  asset_tag varchar unique not null,
  type equipment_type not null,
  last_location_id integer references locations(id),
  o2_full boolean);

CREATE TABLE reasons(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type reason_type not null,
  code varchar not null,
  label varchar not null);
  CREATE UNIQUE INDEX reasons_type_code_key ON reasons(type, code);

CREATE TABLE recurring_runs(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar not null,
  type request_type not null,
  from_location_id integer not null references locations(id),
  to_location_id integer references locations(id),
  rotation varchar[],
  times_of_day varchar[] not null,
  next_rotation_index integer not null default 0,
  active boolean not null default true);

CREATE TABLE requests(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type request_type not null,
    priority priority not null,
    status request_status not null default 'NEW',
    escalated boolean not null default false,
    delay_reason_id integer references reasons(id),
    department_id integer not null references departments(id),
    requested_by integer not null references users(id),
    from_location_id integer references locations(id),
    from_room varchar,
    to_location_id integer not null references locations(id),
    to_room varchar,
    patient_id integer references patients(id),
    trip_purpose trip_purpose,
    transport_mode transport_mode,
    transport_brings_equipment boolean not null default false,
    clinical_requirements varchar[],
    isolation_type isolation_type,
    equipment_type equipment_type,
    quantity integer,
    equipment_id integer references equipment(id),
    postponed_until timestamptz,
    scheduled_for timestamptz,
    recurring_run_id integer references recurring_runs(id),
    notes varchar,
    version integer not null default 0,
    created_at timestamptz not null default now(),
    assigned_at timestamptz);
    CREATE INDEX requests_status_priority_created_at_idx ON requests(status, priority, created_at);

CREATE TABLE request_assignments(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id integer not null references requests(id),
    user_id integer not null references users(id),
    assigned_by assigned_by not null,
    assigned_at timestamptz not null default now(),
    acknowledged_at timestamptz,
    removed_at timestamptz,
    reason varchar);

CREATE TABLE request_events(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id integer not null references requests(id),
    status request_status not null,
    changed_by integer  references users(id),
    reason_id integer references reasons(id),
    note varchar,
    created_at timestamptz not null default now());

CREATE TABLE messages(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id integer references requests(id),
    from_user_id integer not null references users(id),
    to_user_id integer references users(id),
    body varchar not null,
    created_at timestamptz not null default now(),
    read_at timestamptz);

CREATE TABLE shifts(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer not null references users(id),
    signed_in_at timestamptz not null default now(),
    signed_out_at timestamptz);

CREATE TABLE shift_sectors(shift_id integer not null references shifts(id),
    sector_id integer not null references sectors(id),
    rank sector_rank not null,
    PRIMARY KEY (shift_id, sector_id));

CREATE TABLE breaks(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
   shift_id integer not null references shifts(id),
   started_at timestamptz not null default now(),
   ended_at timestamptz,
   started_by integer references users(id));

CREATE TABLE location_links(
    from_id integer not null references locations(id),
    to_id integer not null references locations(id),
    travel_seconds integer not null,
    PRIMARY KEY (from_id, to_id));





